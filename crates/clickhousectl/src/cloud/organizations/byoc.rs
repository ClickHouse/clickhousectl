/// The enrollment token body; an omitted `--ttl-seconds` sends `{}`, so the
/// server's default lifetime applies.
pub(super) fn build_byoc_enrollment_token_request(
    ttl_seconds: Option<i64>,
) -> ByocInfrastructureEnrollmentTokenPostRequest {
    ByocInfrastructureEnrollmentTokenPostRequest { ttl_seconds }
}

/// The human confirmation of `enrollment-token`. The token is a one-time
/// secret, so a response without it is an error rather than a silent success.
fn render_enrollment_token(
    byoc_id: &str,
    enrollment: &ByocInfrastructureEnrollmentToken,
) -> CloudResult<String> {
    let token = enrollment.token.as_deref().ok_or_else(|| {
        CloudError::new(format!(
            "the API response omitted the enrollment token for BYOC infrastructure {byoc_id}, \
             so it cannot be shown; create another with `cloud org byoc enrollment-token {byoc_id}`"
        ))
    })?;
    let mut out = String::from("Enrollment token created!\n");
    out.push_str(&format!("  Token: {token}\n"));
    out.push_str(&format!(
        "  Expires: {}\n",
        or_absent(enrollment.expires_at.map(format_rfc3339))
    ));
    out.push('\n');
    out.push_str("Save the token now — it will not be shown again.\n");
    Ok(out)
}

pub(super) async fn byoc_enrollment_token(
    client: &CloudClient,
    byoc_id: &str,
    request: ByocInfrastructureEnrollmentTokenPostRequest,
    json: bool,
) -> CloudResult<()> {
    let org_id = resolve_org_id(client).await?;
    let enrollment = client
        .create_byoc_enrollment_token(&org_id, byoc_id, &request)
        .await?;
    // Check before either output branch: the token is returned only once.
    let human = render_enrollment_token(byoc_id, &enrollment)?;
    if json {
        println!("{}", serde_json::to_string_pretty(&enrollment)?);
    } else {
        print!("{human}");
    }
    Ok(())
}

